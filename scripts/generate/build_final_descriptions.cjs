// ════════ BUILD OUTPUT ════════
const output = {};
let fromDetailed = 0;
let fromReusable = 0;
let fromPatterns = 0;
let missing = 0;

for (const [wiki, meta] of polities) {
  const zhName = zhNameMap[meta.name] || null;
  let desc = null;

  // Priority 1: DETAILED dict
  desc = DETAILED[wiki] || DETAILED[meta.name] || null;

  // Fuzzy match DETAILED
  if (!desc) {
    for (const [key, val] of Object.entries(DETAILED)) {
      if (val && (wiki.startsWith(key + ' ') || wiki.startsWith(key + '(') || wiki === key ||
          wiki.toLowerCase().includes(key.toLowerCase()) || (meta.name && meta.name.includes(key)))) {
        desc = val;
        break;
      }
    }
  }

  if (desc) {
    fromDetailed++;
  }

  // Priority 2: Reusable existing descriptions (if no detailed)
  if (!desc && reusable[wiki]) {
    desc = reusable[wiki];
    fromReusable++;
  }

  // Priority 3: Pattern generation (if still nothing)
  if (!desc) {
    for (const p of PATTERNS) {
      const m = meta.name.match(p.test);
      if (m) { desc = p.fn(m); fromPatterns++; break; }
    }
  }

  if (!desc) {
    missing++;
  }

  const clean = { name: meta.name, from: meta.from, to: meta.to };
  if (desc) {
    clean.zh = { title: zhName || meta.name, extract: desc, thumbnail: null };
  }
  output[wiki] = clean;
}

// Write
fs.writeFileSync(OUTPUT_FILE, JSON.stringify(output, null, 2), 'utf-8');

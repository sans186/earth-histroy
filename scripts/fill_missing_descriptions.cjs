const output = { ...existing };
let filledDetailed = 0;
let filledPattern = 0;
let stillMissing = 0;

for (const [wiki, meta] of polities) {
  if (output[wiki] && output[wiki].zh) continue; // already has description

  const zhName = zhNameMap[meta.name] || null;
  let desc = null;
  const name = meta.name;

  // Try matching by wiki key
  desc = MORE[wiki] || null;

  // Try matching by name
  if (!desc) desc = NAME_MAP[name] || null;

  // Try matching NAME_MAP by wiki key
  if (!desc) desc = NAME_MAP[wiki] || null;

  // Try case-insensitive matching in MORE
  if (!desc) {
    for (const [key, val] of Object.entries(MORE)) {
      if (key.toLowerCase() === wiki.toLowerCase() || key.toLowerCase() === name.toLowerCase()) {
        desc = val; break;
      }
    }
  }

  if (desc) { filledDetailed++; }

  // Patterns (on name)
  if (!desc) {
    for (const p of PATTERNS) {
      const m = name.match(p.test);
      if (m) { desc = p.fn(m); if (desc === null) break; filledPattern++; break; }
    }
  }

  if (desc) {
    output[wiki] = {
      name: meta.name,
      from: meta.from,
      to: meta.to,
      zh: { title: zhName || meta.name, extract: desc, thumbnail: null }
    };
  } else {
    stillMissing++;
  }
}

// Write

// ── Pattern-based description templates ──
function generateDescription(name, wiki) {
  // Kingdoms
  const koMatch = name.match(/^Kingdom of (.+)$/i);
  if (koMatch) {
    const base = koMatch[1];
    return `${base}王国是中世纪至近代欧洲的重要王国，在欧洲历史上发挥了重要作用。`;
  }

  // Republics
  const roMatch = name.match(/^Republic of (.+)$/i);
  if (roMatch) {
    const base = roMatch[1];
    return `${base}共和国是历史上存在的共和国政权。`;
  }

  // Empires
  const eoMatch = name.match(/^Empire of (.+)$/i);
  if (eoMatch) {
    const base = eoMatch[1];
    return `${base}帝国是历史上重要的帝国政权，在其鼎盛时期拥有广阔的领土和强大的影响力。`;
  }

  // X Empire
  const eMatch = name.match(/^(.+)\s+Empire$/i);
  if (eMatch) {
    const base = eMatch[1];
    return `${base}帝国是历史上重要的帝国政权。`;
  }

  // X Kingdom
  const kMatch = name.match(/^(.+)\s+Kingdom$/i);
  if (kMatch) {
    const base = kMatch[1];
    return `${base}王国是历史上重要的王国，在欧洲历史中占有一席之地。`;
  }

  // X Republic
  const rMatch = name.match(/^(.+)\s+Republic$/i);
  if (rMatch) {
    const base = rMatch[1];
    return `${base}共和国是历史上存在的共和制政权。`;
  }

  // Duchy of X
  const dMatch = name.match(/^Duchy of (.+)$/i);
  if (dMatch) {
    const base = dMatch[1];
    return `${base}公国是欧洲中世纪至近代的封建公国，在神圣罗马帝国体系中占有一席之地。`;
  }

  // Principality of X
  const pMatch = name.match(/^Principality of (.+)$/i);
  if (pMatch) {
    const base = pMatch[1];
    return `${base}公国是欧洲历史上的封建公国。`;
  }

  // Sultanate of X / X Sultanate
  const sMatch = name.match(/^(Sultanate of (.+)|(.+) Sultanate)$/i);
  if (sMatch) {
    const base = sMatch[2] || sMatch[3];
    return `${base}苏丹国是伊斯兰世界的政权，以苏丹为国家元首。`;
  }

  // X Dynasty
  const dynMatch = wiki.match(/^(.+)\s+dynasty$/i) || name.match(/^(.+)\s+(D|d)ynasty$/);
  if (dynMatch) {
    const base = dynMatch[1];
    return `${base}王朝是历史上重要的王朝政权。`;
  }

  return null;
}

// ── Main ──

console.log('Loading polity data...');
const files = fs.readdirSync(POLITIES_DIR).filter(f => f.endsWith('.json') && f !== 'index.json');
const polities = new Map();

for (const file of files) {
  const data = JSON.parse(fs.readFileSync(path.join(POLITIES_DIR, file), 'utf-8'));
  if (!data.features) continue;
  for (const f of data.features) {
    const wiki = f.properties?.Wikipedia;
    const name = f.properties?.Name;
    if (!wiki || !name) continue;
    if (!polities.has(wiki)) {
      polities.set(wiki, { name, from: f.properties.FromYear, to: f.properties.ToYear });
    }
  }
}

console.log(`  → ${polities.size} unique polities`);

// Generate output
const output = {};
let withDescription = 0;
let withPattern = 0;
let without = 0;

for (const [wiki, meta] of polities) {
  const zhName = zhNameMap[meta.name] || null;

  // Try exact match first
  let desc = DESCRIPTIONS[wiki] || DESCRIPTIONS[meta.name] || null;

  // Try matching by checking if wiki starts with any key
  if (!desc) {
    for (const [key, val] of Object.entries(DESCRIPTIONS)) {
      if (wiki.startsWith(key + ' ') || wiki.startsWith(key + '(') || wiki === key) {
        desc = val;
        break;
      }
    }
  }

  // Try pattern generation
  if (!desc) {
    desc = generateDescription(meta.name, wiki);
    if (desc) withPattern++;
  }

  if (desc) {
    withDescription++;
  } else {
    without++;
  }

  const clean = { name: meta.name, from: meta.from, to: meta.to };
  if (desc) {
    clean.zh = { title: zhName || meta.name, extract: desc, thumbnail: null };
  }
  output[wiki] = clean;
}

// Write output
fs.writeFileSync(OUTPUT_FILE, JSON.stringify(output, null, 2), 'utf-8');
const stats = fs.statSync(OUTPUT_FILE);
console.log(`\nWritten: ${Object.keys(output).length} entries`);
console.log(`  - Exact known descriptions: ${withDescription - withPattern}`);
console.log(`  - Pattern-generated: ${withPattern}`);
console.log(`  - Missing: ${without}`);
console.log(`  - File: ${(stats.size / 1024 / 1024).toFixed(2)} MB`);

// List missing
if (without > 0) {
  console.log('\nMissing descriptions:');
  let count = 0;
  for (const [wiki, entry] of Object.entries(output)) {
    if (!entry.zh) {
      console.log(`  ${wiki} (${entry.name})`);
      count++;
      if (count >= 30) { console.log(`  ... and ${without - 30} more`); break; }
    }
  }
}

console.log('Collecting polity data...');
const files = fs.readdirSync(POLITIES_DIR).filter(f => f.endsWith('.json') && f !== 'index.json');
const polities = new Map();

for (const file of files) {
  const data = JSON.parse(fs.readFileSync(path.join(POLITIES_DIR, file), 'utf-8'));
  if (!data.features) continue;
  for (const f of data.features) {
    const wiki = f.properties?.Wikipedia;
    const name = f.properties?.Name;
    if (!wiki || !name) continue;
    if (!polities.has(wiki)) {
      polities.set(wiki, { name, from: f.properties.FromYear, to: f.properties.ToYear });
    }
  }
}

console.log(`  → ${polities.size} polities`);

const output = {};
let detailedCount = 0;
let patternCount = 0;
let missingCount = 0;

for (const [wiki, meta] of polities) {
  const zhName = zhNameMap[meta.name] || null;

  // 1. Try detailed description
  let desc = DETAILED[wiki] || DETAILED[meta.name] || null;

  // Try fuzzy match
  if (!desc) {
    for (const [key, val] of Object.entries(DETAILED)) {
      if (wiki.startsWith(key + ' ') || wiki.startsWith(key + '(') || wiki.endsWith(' ' + key) || wiki === key) {
        desc = val;
        break;
      }
    }
  }

  // 2. Try pattern match
  if (!desc) {
    for (const p of PATTERNS) {
      const m = meta.name.match(p.test) || wiki.match(p.test);
      if (m) { desc = p.tmpl(m); patternCount++; break; }
    }
  }

  // 3. Also try DETAILED for some well-known names in other patterns
  if (!desc) {
    // Check the English name against DETAILED
    for (const [key, val] of Object.entries(DETAILED)) {
      if (meta.name.toLowerCase() === key.toLowerCase() ||
          meta.name.toLowerCase().startsWith(key.toLowerCase())) {
        desc = val;
        break;
      }
    }
  }

  if (desc) {
    detailedCount++;
  } else {
    missingCount++;
  }

  const clean = { name: meta.name, from: meta.from, to: meta.to };
  if (desc) {
    clean.zh = { title: zhName || meta.name, extract: desc, thumbnail: null };
  }
  output[wiki] = clean;
}

// Write output
fs.writeFileSync(OUTPUT_FILE, JSON.stringify(output, null, 2), 'utf-8');
const stats = fs.statSync(OUTPUT_FILE);

console.log(`\nDone:`);
console.log(`  - Detailed descriptions: ${detailedCount}`);
console.log(`  - Pattern-generated: ${patternCount}`);
console.log(`  - Missing: ${missingCount}`);
